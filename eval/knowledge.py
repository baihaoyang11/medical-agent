def build_queries() -> List[tuple]:
    """把知识点展开成 query 列表：(query, point_key, qtype, style)。"""
    out = []
    for p in POINTS:
        out.append((p.formal, p.key, p.qtype, "formal"))
        out.append((p.colloquial, p.key, p.qtype, "colloquial"))
    return out


