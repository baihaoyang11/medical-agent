"""评测语料的知识点定义。

设计原则
--------
1. **8 个主题 × 6 个侧面 = 48 个知识点**。同一主题内，六个侧面互为"难负样本"——
   都讲糖尿病，但饮食/用药/运动是不同的事。检索器必须区分到侧面这一层，
   而不是停在主题层。
2. **每个知识点配两种问法**：
   - `formal`：书面表述，与正文词面重合度高，BM25 能吃到
   - `colloquial`：口语表述，与正文几乎不共享词，必须靠语义匹配
   这个设计让"纯 BM25"和"纯向量"各自只能覆盖一半，混合检索才有意义。
3. 语料是**合成**的，不是真实教材。原因：真实教材受著作权保护，不能随仓库分发
   （见 README 已知边界第 7 条）。合成语料能保证仓库可复现、可公开，
   代价是它测的是"检索器在受控难度下的相对表现"，不等于真实业务效果。

医学表述尽量使用教科书级结论，不给具体剂量，避免写出有风险的内容。
"""

